import {copyFileSync,mkdirSync,mkdtempSync,readFileSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root=resolve(import.meta.dirname,'../..');
const out=mkdtempSync(join(root,'platform/backend/target/native-identity-release-'));
const files=[];
const copy=(from,to)=>{copyFileSync(join(root,from),join(out,to));files.push(to);};
for(const dir of ['bridge','backend','web'])mkdirSync(join(out,dir));
copy('platform/backend/target/native-identity-runtime-uUaUAE/runtime/identity-bridge','bridge/identity-bridge');
copy('platform/backend/target/native-identity-runtime-uUaUAE/runtime/Dockerfile','bridge/Dockerfile');
copy('platform/backend/target/erp-backend-0.1.0-SNAPSHOT.jar','backend/app.jar');
writeFileSync(join(out,'backend/Dockerfile'),'FROM xz-erp-backend:20260905T131900Z-shared-erp-f83c0b0f\nCOPY app.jar /app/app.jar\n');files.push('backend/Dockerfile');
copy('platform/backend/target/native-identity-web-SvXMiK/runtime/dist.tar','web/dist.tar');
copy('platform/backend/target/native-identity-web-SvXMiK/runtime/Dockerfile','web/Dockerfile');
for(const file of ['native-cs-runtime-install.sql','erp-identity.sql','native-erp-runtime-bindings.sql'])copy('platform/preparation/sql/'+file,file);
copy('platform/scripts/deploy-native-identity-runtime.py','deploy.py');
const manifest=files.map(file=>({file,sha256:createHash('sha256').update(readFileSync(join(out,file))).digest('hex')}));
writeFileSync(join(out,'manifest.json'),JSON.stringify(manifest,null,2));
const r=spawnSync('tar',['-cf',join(out,'release.tar'),'-C',out,...files,'manifest.json'],{windowsHide:true,encoding:'utf8'});
if(r.status!==0)throw Error('ARCHIVE_FAILED');console.log(out);
